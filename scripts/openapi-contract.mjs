import { readFile, writeFile } from "node:fs/promises";

const specPath = new URL("../openapi.json", import.meta.url);
const routesPath = new URL("../packages/platform/src/api-routes.ts", import.meta.url);
const spec = JSON.parse(await readFile(specPath, "utf8"));
const operations = {};
const operationIds = new Set();
const refs = [];
const visit = (value) => {
  if (!value || typeof value !== "object") return;
  if (typeof value.$ref === "string") refs.push(value.$ref);
  Object.values(value).forEach(visit);
};
visit(spec);
if (spec.openapi !== "3.1.0" || !spec.paths || !spec.components?.schemas) throw new Error("Expected an OpenAPI 3.1 document.");
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = item[method];
    if (!operation) continue;
    if (!operation.operationId || operationIds.has(operation.operationId)) throw new Error(`Invalid operationId at ${method.toUpperCase()} ${path}.`);
    operationIds.add(operation.operationId);
    operations[operation.operationId] = { method: method.toUpperCase(), path };
  }
}
for (const ref of refs) {
  if (!ref.startsWith("#/")) throw new Error(`External reference is not allowed: ${ref}`);
  const found = ref.slice(2).split("/").reduce((value, key) => value?.[key.replaceAll("~1", "/").replaceAll("~0", "~")], spec);
  if (!found) throw new Error(`Unresolved reference: ${ref}`);
}
const generated = `// Generated by npm run api:generate. Do not edit.\nexport const apiOperations = ${JSON.stringify(operations, null, 2)} as const;\nexport type ApiOperationId = keyof typeof apiOperations;\nexport type ApiPath = (typeof apiOperations)[ApiOperationId]["path"];\n`;
if (process.argv.includes("--check")) {
  if (await readFile(routesPath, "utf8").catch(() => "") !== generated) throw new Error("Generated API routes are stale. Run npm run api:generate.");
  const sources = await Promise.all(["../apps/desktop/src/adapters.ts", "../apps/web/src/adapters.ts"].map(async (path) => readFile(new URL(path, import.meta.url), "utf8")));
  const known = new Set(Object.values(operations).map(({ path }) => path));
  for (const source of sources) for (const match of source.matchAll(/(?:request|post)\("(\/[^"?]+)"|new URL\("(\/[^"?]+)"/g)) {
    const path = match[1] ?? match[2];
    if (!known.has(path)) throw new Error(`Client route is absent from OpenAPI: ${path}`);
  }
  console.log(`OpenAPI contract valid: ${Object.keys(operations).length} operations.`);
} else {
  await writeFile(routesPath, generated);
  console.log(`Generated ${Object.keys(operations).length} API operations.`);
}
